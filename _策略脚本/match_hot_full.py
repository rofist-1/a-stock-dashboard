results = []

for date_str in sorted(daily_stocks.keys()):
    hot_today = daily_hot[date_str]
    
    for code, name in daily_stocks[date_str]:
        matched = []
        for sector in hot_today:
            if sector in sector_stocks and code in sector_stocks[sector]:
                matched.append(sector)
        if matched:
            results.append((date_str, code, name, "是", "; ".join(matched[:3])))
